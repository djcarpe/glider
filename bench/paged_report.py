#!/usr/bin/env python3
"""Turn ../glider-bench-data/scale/paged-results.jsonl (from bench/paged_scale.py) into
a Markdown report, compared with the snapshot-image engine's run
(../glider-bench-data/scale/results.jsonl, from bench/scale.py) and the 100 GB
page-store gate (../glider-bench-data/pb/gate.jsonl, from pagebench).

    python3 bench/paged_report.py > bench/PAGED.md
"""

import json
import os
import sys
from collections import defaultdict

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from scale_report import gb, load, mb, ms, table  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# Datasets live outside the repo: Rustler (glider_ex) digests every file under
# a path-dependency crate on each compile, so multi-GB files here OOM it.
BENCH_DATA = os.environ.get("GLIDER_BENCH_DATA", os.path.join(os.path.dirname(ROOT), "glider-bench-data"))
DATA = os.path.join(BENCH_DATA, "scale")
SIZES = ["1GiB", "5GiB", "10GiB", "25GiB"]
PAGED = ["cache 1 GiB (default)", "cache 64 MiB"]
IMAGE = "image, lazy (default)"
OLD = "log, old build (replay)"


def group(rs):
    by = defaultdict(list)
    for r in rs:
        by[r["phase"]].append(r)
    return by


def find(rs, **kw):
    return next((r for r in rs if all(r.get(k) == v for k, v in kw.items())), None)


def cell(r, key="wall_s"):
    if r is None:
        return "—"
    if not r.get("ok", True):
        err = (r.get("error") or "")
        why = "out of memory" if ("memory" in err.lower() or "exit -6" in err or "exit 134" in err or "alloc" in err.lower()) else "failed"
        return f"**{why}**"
    return f"{ms(r[key])} · {mb(r.get('peak_rss_mb'))}"


def qcell(r):
    if r is None:
        return "—"
    if not r["ok"]:
        return "**failed**" + (" (timeout)" if r.get("first_s") and r["first_s"] > 590 else "")
    return f"{ms(r['first_s'])} / {ms(r['warm_s'])}"


def main():
    new = group(load(os.path.join(DATA, "paged-results.jsonl")))
    old = group(load(os.path.join(DATA, "results.jsonl")))
    gen = {d["size"]: d for d in load(os.path.join(DATA, "gen.jsonl"))}
    gate = {d["cmd"]: d for d in load(os.path.join(BENCH_DATA, "pb", "gate.jsonl"))}
    sizes = [s for s in SIZES if find(new["file"], size=s) or find(new["build"], size=s)]
    p = print

    p("# glider on paged storage: 1, 5, 10 and 25 GiB\n")
    p("Generated by `bench/paged_scale.py`, rendered by `bench/paged_report.py`. The graphs come from "
      "`scale-gen` with the same generator and seed as the snapshot-image run in [`SCALE.md`](SCALE.md), "
      "so every number here has a counterpart there: same nodes, edges, properties and queries. Each glider "
      "process ran under a 16 GiB address-space cap on a machine with 31 GiB of RAM. **cache 1 GiB** is the "
      "default configuration; **cache 64 MiB** adds `--cache-size 64M --work-mem 64M`, to show what a "
      "small memory budget costs. \"Cold\" means the files were evicted from the OS page cache first. "
      "Times are wall clock; memory is peak RSS unless stated.\n")

    # ------------------------------------------------------------ summary
    p("## Summary\n")
    rows = []
    for s in sizes:
        o_img = find(old["open"], size=s, config=IMAGE, cache="cold")
        o_new = find(new["open"], size=s, config=PAGED[0], cache="cold")
        e_img = find(old["server_end"], size=s, config=IMAGE)
        e_new = find(new["server_end"], size=s, config=PAGED[0])
        e_sml = find(new["server_end"], size=s, config=PAGED[1])
        qi = [r for r in old["query"] if r["size"] == s and r["config"] == IMAGE]
        qn = [r for r in new["query"] if r["size"] == s and r["config"] == PAGED[0]]
        qs = [r for r in new["query"] if r["size"] == s and r["config"] == PAGED[1]]
        rows.append([s,
                     f"{ms((o_img or {}).get('wall_s'))} → {ms((o_new or {}).get('wall_s'))}",
                     f"{mb((e_img or {}).get('hwm_mb'))} → {mb((e_new or {}).get('hwm_mb'))} / {mb((e_sml or {}).get('hwm_mb'))}",
                     f"{sum(1 for r in qi if not r['ok'])} of {len(qi)} → {sum(1 for r in qn if not r['ok'])} of {len(qn)} / {sum(1 for r in qs if not r['ok'])} of {len(qs)}"])
    p(table(["size", "cold open: image → paged", "server peak RSS over all queries: image → paged (1 GiB / 64 MiB cache)",
             "queries failing: image → paged (1 GiB / 64 MiB cache)"], rows))
    p("")

    # ------------------------------------------------------------ datasets
    p("## Datasets and build\n")
    rows = []
    for s in sizes:
        f = find(new["file"], size=s)
        st = (f or {}).get("stats", {})
        b = find(new["build"], size=s, method="bulk load (scale-gen --paged)")
        g = gen.get(f"img-{s}.gldb", {})
        rows.append([s, f"{st.get('nodes', 0):,}", f"{st.get('edges', 0):,}",
                     gb(f["file_bytes"]) if f else "—", gb(f["legacy_image_bytes"]) if f and f.get("legacy_image_bytes") else "—",
                     cell(b), f"{ms(g.get('wall_s'))} · {mb(g.get('peak_rss_kb', 0) / 1024)}" if g else "—"])
    p(table(["size", "nodes", "edges", "paged database", "snapshot image (old)", "paged bulk load (time · RSS)",
             "image build, old (time · RSS)"], rows))
    ins = find(new["build"], method="transactional inserts (scale-gen --paged-insert)")
    if ins:
        p(f"\nThe 1 GiB graph built through the transactional API instead (every node and edge an `add_node` / "
          f"`add_edge` through the write-ahead log): {cell(ins)}, {gb(ins['file_bytes'])}.")
    p("\nThe bulk load sorts everything externally within its working memory and builds each B+tree bottom "
      "up, so its memory does not grow with the graph; the old image builder kept a few integers per node "
      "and edge in RAM. The paged file is larger: one B+tree entry per edge endpoint, plus page slack "
      "(see PAGED-1 in `docs/TODO.md`).\n")

    # ------------------------------------------------------------ open
    p("## Opening\n")
    p("`glider <db> -c STATS`: open, one statement, exit.\n")
    rows = []
    for label, src, cfg in [("paged, cache 1 GiB", new, PAGED[0]), ("paged, cache 64 MiB", new, PAGED[1]),
                            ("snapshot image (old engine)", old, IMAGE), ("log replay (build before images)", old, OLD)]:
        for cache in ("cold", "warm"):
            row = [label, cache]
            got = False
            for s in sizes:
                r = find(src["open"], size=s, config=cfg, cache=cache)
                got |= r is not None
                row.append(cell(r))
            if got:
                rows.append(row)
    p(table(["engine", "cache"] + sizes, rows))
    p("\nOpening a paged database reads one superblock and replays whatever log a crash left behind: "
      "constant time at any size.\n")

    # ------------------------------------------------------------ verify
    if new["verify"]:
        p("## Integrity check (`glider <db> verify`)\n")
        rows = []
        for s in sizes:
            r = find(new["verify"], size=s)
            if r:
                rows.append([s, ms(r["wall_s"]), f"{r['throughput_mb_s']:.0f} MB/s", mb(r["peak_rss_mb"]), "ok" if r["ok"] else "**failed**"])
        p(table(["size", "time (cold)", "rate", "peak RSS", "result"], rows))
        p("\nWalks every B+tree: page checksums, key order and bounds, page ownership, overflow chains.\n")

    # ------------------------------------------------------------ queries
    p("## Queries\n")
    p("One HTTP request per query to `glider <db> serve`, started cold. **first** is the first run in "
      "that server, **warm** the median of the next three (one, when the first took over 10 s).\n")
    names = []
    for r in new["query"]:
        if r["query"] not in names:
            names.append(r["query"])
    for cfg in PAGED:
        qs = [r for r in new["query"] if r["config"] == cfg]
        if not qs:
            continue
        p(f"### Paged, {cfg}\n")
        rows = [[n] + [qcell(find(qs, size=s, query=n)) for s in sizes] for n in names]
        p(table(["query (first / warm)"] + sizes, rows))
        p("")
        rows = []
        for s in sizes:
            a = find(new["server_start"], size=s, config=cfg)
            b = find(new["server_end"], size=s, config=cfg)
            if a:
                rows.append([s, ms(a.get("wall_s")), mb(a.get("rss_mb")), mb((b or {}).get("rss_mb")), mb((b or {}).get("hwm_mb"))])
        p(table(["size", "server start (cold)", "RSS after start", "RSS after all queries", "peak RSS"], rows))
        p("")

    p("### Against the snapshot-image engine\n")
    p("Warm time, paged (1 GiB cache) vs the image engine's default configuration, and whether the "
      "results agree (first 300 characters of the JSON rows, as recorded).\n")
    for s in sizes:
        qi = {r["query"]: r for r in old["query"] if r["size"] == s and r["config"] == IMAGE}
        if not qi:
            continue
        rows = []
        for n in names:
            a = qi.get(n)
            b = find(new["query"], size=s, config=PAGED[0], query=n)
            if a is None and b is None:
                continue
            same = "—"
            if a and b and a["ok"] and b["ok"]:
                same = "yes" if a.get("result") == b.get("result") else ("by design" if n in ("STATS", "SCHEMA") else "**no**")
            fmt = lambda r: "—" if r is None else (ms(r["warm_s"] or r["first_s"]) if r["ok"] else "**failed**")
            rows.append([n, fmt(a), fmt(b), same])
        p(f"**{s}**\n")
        p(table(["query", "image (warm)", "paged (warm)", "same result"], rows))
        e_img = find(old["server_end"], size=s, config=IMAGE)
        e_new = find(new["server_end"], size=s, config=PAGED[0])
        p(f"\nServer peak RSS: image {mb((e_img or {}).get('hwm_mb'))}, paged {mb((e_new or {}).get('hwm_mb'))}.\n")

    # ------------------------------------------------------------ api
    if new["api"]:
        p("## Browsing API (`/api/*`, `/stats`)\n")
        an = []
        for r in new["api"]:
            if r["query"] not in an:
                an.append(r["query"])
        for cfg in PAGED:
            rs = [r for r in new["api"] if r["config"] == cfg]
            if not rs:
                continue
            p(f"### Paged, {cfg}\n")
            rows = [[n] + [qcell(find(rs, size=s, query=n)) for s in sizes] for n in an]
            p(table(["request (first / warm)"] + sizes, rows))
            p("")

    # ------------------------------------------------------------ load
    if new["load"]:
        p("## Concurrent reads (`loadgen`, indexed 1-hop queries)\n")
        rows = []
        for s in sizes:
            for r in [x for x in new["load"] if x["size"] == s]:
                j = r["result"]
                o = next((x for x in old["load"] if x["size"] == s and x["clients"] == r["clients"]), None)
                oj = (o or {}).get("result", {})
                rows.append([s, r["clients"], f"{j.get('throughput', j.get('qps', '—'))}",
                             f"{oj.get('throughput', oj.get('qps', '—'))}" if o else "—",
                             f"{j.get('p50_ms', '—')}", f"{j.get('p99_ms', '—')}", mb(r.get("rss_mb"))])
        p(table(["size", "clients", "queries/s", "queries/s, image engine", "p50 ms", "p99 ms", "server RSS"], rows))
        p("")

    # ------------------------------------------------------------ writes
    if new["write"]:
        p("## Writes\n")
        p("Per statement, open excluded; each statement its own transaction.\n")
        ops = []
        for r in new["write"]:
            if r["op"] not in ops:
                ops.append(r["op"])
        rows = []
        for o in ops:
            row = [o]
            for s in sizes:
                r = find(new["write"], size=s, op=o)
                row.append("—" if r is None else (f"{r['per_op_ms']:.2f} ms" if r["ok"] else "**failed**"))
            rows.append(row)
        p(table(["operation"] + sizes, rows))
        oo = [r for r in old["write"] if r["size"] in sizes]
        if oo:
            p("\nThe image engine, for comparison (writes went to an in-memory delta and a log):\n")
            ops = []
            for r in oo:
                if r["op"] not in ops:
                    ops.append(r["op"])
            rows = [[o] + [(lambda r: "—" if r is None else (f"{r['per_op_ms']:.2f} ms" if r["ok"] else "**failed**"))(find(oo, size=s, op=o)) for s in sizes] for o in ops]
            p(table(["operation (image engine)"] + sizes, rows))
        p("")

    # ------------------------------------------------------------ recovery / checkpoint
    if new["recovery"] or new["checkpoint"]:
        p("## Crash recovery and checkpoints\n")
        rows = []
        for s in sizes:
            r = find(new["recovery"], size=s)
            c = find(new["checkpoint"], size=s)
            oc = find(old["compact"], size=s)
            rows.append([s,
                         f"{(r or {}).get('log_bytes', 0) / (1 << 20):.1f} MiB" if r else "—",
                         f"{ms(r['wall_s'])} · {mb(r['peak_rss_mb'])}" if r and r["ok"] else ("**failed**" if r else "—"),
                         "ok" if (r or {}).get("verify_ok") else ("**failed**" if r else "—"),
                         f"{(c or {}).get('log_bytes', 0) / (1 << 20):.1f} MiB in {ms(c['wall_s'])}" if c and c["ok"] else ("**failed**" if c else "—"),
                         (f"{ms(oc['wall_s'])} · {mb(oc['peak_rss_mb'])}" if oc and oc["ok"] else ("**failed**" if oc else "—"))])
        p(table(["size", "log left by kill -9", "reopen: replay (time · RSS)", "verify after", "checkpoint",
                 "old engine COMPACT (time · RSS)"], rows))
        p("\nA writer running a stream of autocommit statements with checkpoints off is killed with SIGKILL; "
          "the next open replays the committed log and a full `verify` follows. A checkpoint writes only the "
          "pages changed since the last one, where the old engine's compaction rewrote the whole file.\n")

    # ------------------------------------------------------------ replication / export
    if new["replicate_base"] or new["export"]:
        p("## Replication and export\n")
        rows = []
        for s in sizes:
            a = find(new["replicate_base"], size=s)
            b = find(new["replicate_log"], size=s)
            c = find(new["replicate_restore"], size=s)
            o = find(old["replicate_ship"], size=s)
            if a:
                rows.append([s, f"{ms(a['wall_s'])} ({a['throughput_mb_s']:.0f} MB/s) · {mb(a['peak_rss_mb'])}",
                             ms((b or {}).get("wall_s")), cell(c), "yes" if (c or {}).get("same_counts") else "**no**",
                             f"{ms(o['wall_s'])} · {mb(o['peak_rss_mb'])}" if o and o["ok"] else "—"])
        if rows:
            p(table(["size", "`wal tail --once`: base copy", "then: ship 5,000 commits", "`wal restore` (base + log replay)",
                     "restored counts match", "old engine: ship whole file"], rows))
            p("")
        rows = []
        for s in sizes:
            e = find(new["export"], size=s)
            i = find(new["import"], size=s)
            c = find(new["roundtrip_check"], size=s)
            if e:
                rows.append([s, f"{cell(e)} · {gb(e['jsonl_bytes'])} JSONL", cell(i), "yes" if (c or {}).get("same_counts") else "**no**"])
        if rows:
            p(table(["size", "export (time · RSS · output)", "import into a new file (time · RSS)", "counts survive"], rows))
            p("")

    # ------------------------------------------------------------ memory
    m = find(new["memory_limit"])
    if m:
        j = m.get("result", {})
        p("## `:memory:` with a limit\n")
        p(f"`pagebench memfill --max-mb 256` inserts until the graph is full: after "
          f"{j.get('committed_entries', 0):,} committed entries the next write failed with "
          f"\"{j.get('full_message', '')}\", was rolled back, and the graph stayed readable and writable "
          f"(deletes, then more inserts) — {ms(m['wall_s'])}, peak RSS {mb(m['peak_rss_mb'])}.\n")

    # ------------------------------------------------------------ 100 GB
    if gate:
        b = gate.get("build", {})
        p("## The page store at 100 GB\n")
        p("`pagebench` against the storage layer directly, with the default 1 GiB page cache "
          "(`../glider-bench-data/pb/gate.jsonl`):\n")
        rows = []
        if b:
            rows.append(["build (bulk, bottom-up)", f"{b['entries']:,} entries, {gb(b['file_bytes'])} in {ms(b['seconds'])} "
                         f"({b['mb_s']:.0f} MB/s)", mb(b["peak_rss_mb"])])
        for k, label in [("lookups_cold", "point lookups, cold"), ("lookups_warm", "point lookups, warm"),
                         ("lookups_after_update", "point lookups after updates")]:
            r = gate.get(k)
            if r:
                rows.append([label, f"open {ms(r['open_s'])}; p50 {r['p50_us'] / 1000:.2f} ms, p99 {r['p99_us'] / 1000:.2f} ms, "
                             f"{r['disk_reads_per_lookup']:.2f} disk reads each (tree height {r['height']})", mb(r["peak_rss_mb"])])
        r = gate.get("scan")
        if r:
            rows.append(["full scan", f"{r['entries_s']:,} entries/s, {r['file_mb_s']:.0f} MB/s", mb(r["peak_rss_mb"])])
        r = gate.get("update")
        if r:
            rows.append(["random updates", f"{r['ops_s']:,} ops/s in transactions of {r['per']}", mb(r["peak_rss_mb"])])
        p(table(["operation", "result", "peak RSS"], rows))
        p("\nAnd `pagebench crashloop`: 25 kill -9s mid-write under `--sync always` and 25 under `normal`, "
          "each reopened and checked against the last acknowledged commit — all recovered.\n")


if __name__ == "__main__":
    main()
