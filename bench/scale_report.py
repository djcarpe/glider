#!/usr/bin/env python3
"""Turn ../glider-bench-data/scale/results.jsonl (from bench/scale.py) into a
Markdown report.

    python3 bench/scale_report.py > bench/SCALE.md
"""

import json
import os
import sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# Datasets live outside the repo: Rustler (glider_ex) digests every file under
# a path-dependency crate on each compile, so multi-GB files here OOM it.
BENCH_DATA = os.environ.get("GLIDER_BENCH_DATA", os.path.join(os.path.dirname(ROOT), "glider-bench-data"))
DATA = os.path.join(BENCH_DATA, "scale")
SIZES = ["1GiB", "5GiB", "10GiB", "25GiB"]


def load(path):
    out = []
    if os.path.exists(path):
        for line in open(path):
            line = line.strip()
            if line:
                out.append(json.loads(line))
    return out


def ms(s):
    if s is None:
        return "—"
    if s < 1:
        return f"{s * 1000:.1f} ms" if s < 0.1 else f"{s * 1000:.0f} ms"
    if s < 60:
        return f"{s:.2f} s"
    return f"{s / 60:.1f} min"


def mb(x):
    if x is None:
        return "—"
    return f"{x / 1024:.2f} GB" if x >= 1024 else f"{x:.0f} MB"


def gb(b):
    return f"{b / (1 << 30):.2f} GiB"


def table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(c) for c in r) + " |")
    return "\n".join(out)


def main():
    results = load(sys.argv[1] if len(sys.argv) > 1 else os.path.join(DATA, "results.jsonl"))
    gen = {d["size"]: d for d in load(os.path.join(DATA, "gen.jsonl"))}
    by = defaultdict(list)
    for r in results:
        by[r["phase"]].append(r)
    sizes = [s for s in SIZES if any(r.get("size") == s for r in results)]
    p = print

    p("# glider at scale: 1, 5, 10 and 25 GiB\n")
    p("Generated by `bench/scale.py` from files built by `scale-gen`; "
      "rendered by `bench/scale_report.py`. Every glider process ran under a 16 GiB "
      "address-space cap on a machine with 31 GiB of RAM (about 18 GiB free). "
      "\"Old build\" is the commit before snapshot images (11b80df), which replays the whole "
      "log on open. \"Cold\" means the file was evicted from the page cache first.\n")

    # ---------------------------------------------------------------- data
    p("## Datasets\n")
    rows = []
    for s in sizes:
        f = next((r for r in by["file"] if r["size"] == s), None)
        g = gen.get(f"img-{s}.gldb", {})
        st = (f or {}).get("stats", {})
        rows.append([s, f"{st.get('nodes', '—'):,}" if st else "—", f"{st.get('edges', '—'):,}" if st else "—",
                     gb(f["file_bytes"]) if f else "—", ms(g.get("wall_s")), mb(g.get("peak_rss_kb", 0) / 1024) if g else "—",
                     f"{g['bytes'] / (1 << 20) / g['wall_s']:.0f} MB/s" if g else "—"])
    p(table(["size", "nodes", "edges", "file", "build time", "build peak RSS", "build rate"], rows))
    p("\nBuilt directly as snapshot images with `glider::image::build`, which streams "
      "properties to disk and keeps only a few integers per node and edge. "
      "The same generator also wrote the 1 GiB and 5 GiB graphs as plain logs for the old build; "
      "at 300k ids, replaying such a log and compacting it produced an image byte-identical to the "
      "direct build.\n")
    for s in sizes:
        lg = gen.get(f"log-{s}.gldb")
        if lg:
            p(f"- log form of {s}: {gb(lg['bytes'])}, written in {ms(lg['wall_s'])} at {mb(lg['peak_rss_kb'] / 1024)} peak RSS")
    p("")
    f = next((r for r in by["file"] if r.get("groups")), None)
    if f:
        p("### What the file is made of\n")
        rows = []
        for s in sizes:
            fr = next((r for r in by["file"] if r["size"] == s and r.get("groups")), None)
            if not fr:
                continue
            tot = fr["file_bytes"]
            rows.append([s] + [f"{fr['groups'][k] / tot * 100:.1f}%" for k in ["properties", "adjacency", "edge_columns", "node_columns", "indexes"]])
        p(table(["size", "property values", "adjacency (both directions)", "edge columns", "node columns", "indexes"], rows))
        p("")

    # ---------------------------------------------------------------- open
    p("## Opening\n")
    p("Time and peak RSS of `glider <db> -c STATS`: open, one statement, exit.\n")
    cfgs = []
    for r in by["open"]:
        if r["config"] not in cfgs:
            cfgs.append(r["config"])
    rows = []
    for c in cfgs:
        for cache in ("cold", "warm"):
            row = [c, cache]
            any_ = False
            for s in sizes:
                r = next((x for x in by["open"] if x["size"] == s and x["config"] == c and x["cache"] == cache), None)
                if r is None:
                    row.append("—")
                elif r["ok"]:
                    any_ = True
                    row.append(f"{ms(r['wall_s'])} · {mb(r['peak_rss_mb'])}")
                else:
                    any_ = True
                    err = (r.get("error") or "")
                    why = "out of memory" if ("memory" in err.lower() or "exit -6" in err or "exit 134" in err or "alloc" in err.lower()) else err.split(":")[0]
                    row.append(f"**fails** ({why}, {ms(r['wall_s'])})")
            if any_:
                rows.append(row)
    p(table(["configuration", "cache"] + sizes, rows))
    p("")

    # -------------------------------------------------------------- verify
    if by["verify"]:
        p("## Integrity check (`glider <db> verify`)\n")
        rows = []
        for s in sizes:
            for cache in ("cold", "warm"):
                r = next((x for x in by["verify"] if x["size"] == s and x["cache"] == cache), None)
                if r:
                    rows.append([s, cache, ms(r["wall_s"]), f"{r['throughput_mb_s']:.0f} MB/s", mb(r["peak_rss_mb"]), "ok" if r["ok"] else "**failed**"])
        p(table(["size", "cache", "time", "rate", "peak RSS", "result"], rows))
        p("\nReads and checksums every byte of the image and log, streaming, without opening the database.\n")

    # ------------------------------------------------------------- queries
    p("## Queries\n")
    p("One HTTP request per query to `glider <db> serve`, started with the file evicted from the page cache. "
      "**first** is the first run in that server — it pays for loading whatever parts of the image the query touches; "
      "**warm** is the median of the next three.\n")
    for cfg in ["image, lazy (default)", "image, props on disk"]:
        qs = [r for r in by["query"] if r["config"] == cfg]
        if not qs:
            continue
        p(f"### {cfg}\n")
        names = []
        for r in qs:
            if r["query"] not in names:
                names.append(r["query"])
        rows = []
        for n in names:
            row = [n]
            for s in sizes:
                r = next((x for x in qs if x["size"] == s and x["query"] == n), None)
                if r is None:
                    row.append("—")
                elif not r["ok"]:
                    row.append("**failed**" + (" (timeout)" if r["first_s"] and r["first_s"] > 590 else ""))
                else:
                    row.append(f"{ms(r['first_s'])} / {ms(r['warm_s'])}")
            rows.append(row)
        p(table(["query (first / warm)"] + sizes, rows))
        p("")
        starts = [r for r in by["server_start"] if r["config"] == cfg]
        ends = [r for r in by["server_end"] if r["config"] == cfg]
        rows = []
        for s in sizes:
            a = next((x for x in starts if x["size"] == s), None)
            b = next((x for x in ends if x["size"] == s), None)
            if a:
                rows.append([s, ms(a.get("wall_s")) if a["ok"] else "**failed**", mb(a.get("rss_mb")), mb((b or {}).get("rss_mb")), mb((b or {}).get("hwm_mb"))])
        if rows:
            p(table(["size", "server start (cold)", "RSS after start", "RSS after all queries", "peak RSS"], rows))
            p("")

    # old vs new at 1 GiB
    old = [r for r in by["query"] if r["config"] == "log, old build (replay)"]
    if old:
        p("### Old build vs new, 1 GiB, same queries\n")
        new = {r["query"]: r for r in by["query"] if r["config"] == "image, lazy (default)" and r["size"] == "1GiB"}
        rows = []
        for r in old:
            n = new.get(r["query"])
            same = n is not None and n.get("result") == r.get("result")
            verdict = "yes" if same else ("differs by design (new rows)" if r["query"] == "STATS" else "**no**")
            rows.append([r["query"], f"{ms(r['first_s'])} / {ms(r['warm_s'])}" if r["ok"] else "**failed**",
                         f"{ms(n['first_s'])} / {ms(n['warm_s'])}" if n and n["ok"] else "—", verdict])
        p(table(["query (first / warm)", "old build (log replayed at start)", "new build (lazy image)", "same result"], rows))
        a = next((x for x in by["server_start"] if x["config"] == "log, old build (replay)"), None)
        b = next((x for x in by["server_end"] if x["config"] == "log, old build (replay)"), None)
        if a:
            p(f"\nOld build server start: {ms(a.get('wall_s'))}, RSS {mb(a.get('rss_mb'))} after start, "
              f"peak {mb((b or {}).get('hwm_mb'))}.\n")

    # ----------------------------------------------------------------- api
    if by["api"]:
        p("## Browsing API (`/api/*`, `/stats`)\n")
        names = []
        for r in by["api"]:
            if r["query"] not in names:
                names.append(r["query"])
        for cfg in ["image, lazy (default)", "image, props on disk", "log, old build (replay)"]:
            rs = [r for r in by["api"] if r["config"] == cfg]
            if not rs:
                continue
            p(f"### {cfg}\n")
            rows = []
            for n in names:
                row = [n]
                for s in sizes:
                    r = next((x for x in rs if x["size"] == s and x["query"] == n), None)
                    row.append("—" if r is None else (f"{ms(r['first_s'])} / {ms(r['warm_s'])}" if r["ok"] else "**failed**"))
                rows.append(row)
            p(table(["request (first / warm)"] + sizes, rows))
            p("")

    # ---------------------------------------------------------------- load
    if by["load"]:
        p("## Concurrent reads (`loadgen`, indexed 1-hop queries)\n")
        rows = []
        for s in sizes:
            for r in [x for x in by["load"] if x["size"] == s]:
                j = r["result"]
                rows.append([s, r["clients"], f"{j.get('throughput', j.get('qps', '—'))}",
                             f"{j.get('p50_ms', '—')}", f"{j.get('p99_ms', '—')}", mb(r.get("rss_mb"))])
        p(table(["size", "clients", "queries/s", "p50 ms", "p99 ms", "server RSS"], rows))
        p("\nEvery request is serialised behind one `Mutex<Graph>` and opens a fresh TCP connection, "
          "so throughput is flat in the client count by design; what matters here is that it does not fall with file size.\n")

    # -------------------------------------------------------------- writes
    if by["write"]:
        p("## Writes, compaction, reopening\n")
        ops = []
        for r in by["write"]:
            if r["op"] not in ops:
                ops.append(r["op"])
        rows = []
        for o in ops:
            row = [o]
            for s in sizes:
                r = next((x for x in by["write"] if x["size"] == s and x["op"] == o), None)
                row.append("—" if r is None else (f"{r['per_op_ms']:.2f} ms" if r["ok"] else "**failed**"))
            rows.append(row)
        p(table(["operation (per statement, open excluded)"] + sizes, rows))
        p("")
        rows = []
        for s in sizes:
            t = next((x for x in by["reopen_with_tail"] if x["size"] == s and x["cache"] == "cold"), None)
            tw = next((x for x in by["reopen_with_tail"] if x["size"] == s and x["cache"] == "warm"), None)
            c = next((x for x in by["compact"] if x["size"] == s), None)
            a = next((x for x in by["reopen_after_compact"] if x["size"] == s), None)
            if not (t or c):
                continue
            rows.append([s, f"{(t or {}).get('tail_bytes') or 0:,} B",
                         f"{ms((t or {}).get('wall_s'))} / {ms((tw or {}).get('wall_s'))}",
                         (f"{ms(c['wall_s'])} · {mb(c['peak_rss_mb'])}" if c and c["ok"] else ("**failed**: " + (c or {}).get("error", "")[:60] if c else "—")),
                         f"{c['throughput_mb_s']:.0f} MB/s" if c and c["ok"] else "—",
                         ms((a or {}).get("wall_s"))])
        p(table(["size", "log tail after writes", "reopen with tail (cold / warm)", "COMPACT (time · peak RSS)", "compact rate", "reopen after compact (cold)"], rows))
        p("")

    # --------------------------------------------------------- replication
    if by["replicate_ship"] or by["export"]:
        p("## Replication and export\n")
        rows = []
        for s in sizes:
            a = next((x for x in by["replicate_ship"] if x["size"] == s), None)
            b = next((x for x in by["replicate_restore"] if x["size"] == s), None)
            if a:
                rows.append([s, f"{ms(a['wall_s'])} ({a['throughput_mb_s']:.0f} MB/s)", ms((b or {}).get("wall_s")),
                             "yes" if (b or {}).get("byte_identical") else "**no**"])
        if rows:
            p(table(["size", "`wal tail --once` (ship everything)", "`wal restore`", "restore byte-identical"], rows))
            p("")
        rows = []
        for s in sizes:
            e = next((x for x in by["export"] if x["size"] == s), None)
            i = next((x for x in by["import"] if x["size"] == s), None)
            c = next((x for x in by["roundtrip_check"] if x["size"] == s), None)
            if e:
                rows.append([s, f"{ms(e['wall_s'])} · {mb(e['peak_rss_mb'])} · {gb(e['jsonl_bytes'])} JSONL",
                             f"{ms((i or {}).get('wall_s'))} · {mb((i or {}).get('peak_rss_mb'))}" if i else "—",
                             "yes" if (c or {}).get("same_node_count") else "**no**"])
        if rows:
            p(table(["size", "export (time · RSS · output)", "import into a new file (time · RSS)", "node count survives"], rows))
            p("")


if __name__ == "__main__":
    main()
