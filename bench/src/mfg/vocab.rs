//! Vocabulary for the manufacturing generator: topics, components, makers.
//!
//! A topic is what a work instruction is about (torque, sealing, ...). Each
//! has its own verbs, objects, terms, tools and a specification range, so
//! instructions of one topic share many words and instructions of two
//! topics share only the generic ones in [`OPENERS`] and the sentence
//! frames.

pub struct Topic {
    pub name: &'static str,
    pub verbs: &'static [&'static str],
    pub objects: &'static [&'static str],
    pub terms: &'static [&'static str],
    /// Tool kinds used for this topic.
    pub tools: &'static [&'static str],
    /// Unit, lowest value, highest value, step.
    pub spec: (&'static str, i64, i64, i64),
    pub checks: &'static [&'static str],
}

